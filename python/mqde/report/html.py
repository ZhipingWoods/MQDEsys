# ---------------------------------------------------------------- helpers
def fmt(v: Any, nd: int = 2) -> str:
    if v is None or (isinstance(v, float) and not math.isfinite(v)):
        return "–"
    if isinstance(v, bool):
        return str(v)
    if isinstance(v, int):
        return f"{v:,}"
    return f"{v:,.{nd}f}"


def pct(v: float | None) -> str:
    return "–" if v is None else f"{v:+.2f}%"


def nbytes(v: float | None) -> str:
    if not v:
        return "–"
    for u in ("B", "KiB", "MiB", "GiB", "TiB"):
        if v < 1024 or u == "TiB":
            return f"{v:.0f} {u}" if u == "B" else f"{v:.1f} {u}"
        v /= 1024
    return "–"


def e(s: Any) -> str:
    return escape(str(s))


def table(head: list[tuple[str, bool]], rows: list[list[str]]) -> str:
    th = "".join(f'<th class="{"n" if n else ""}">{e(h)}</th>' for h, n in head)
    body = "".join(
        "<tr>" + "".join(f'<td class="{"n" if head[i][1] else ""}">{c}</td>' for i, c in enumerate(r)) + "</tr>" for r in rows
    )
    return f'<table><thead><tr>{th}</tr></thead><tbody>{body}</tbody></table>'


def bar_chart(labels: list[str], values: list[float | None], title: str, width: int = 960, height: int = 220,
              colour: str = "var(--a)", unit: str = "") -> str:
    vals = [v for v in values if v is not None and math.isfinite(v)]
    if not vals:
        return ""
    lo, hi = min(0.0, min(vals)), max(vals)
    if hi == lo:
        hi = lo + 1
    pad_l, pad_b, pad_t = 44, 26, 8
    n = len(values)
    slot = (width - pad_l - 8) / max(n, 1)
    bw = max(2.0, min(28.0, slot * 0.7))
    y = lambda v: pad_t + (height - pad_t - pad_b) * (1 - (v - lo) / (hi - lo))  # noqa: E731
    parts = [f'<svg viewBox="0 0 {width} {height}" role="img" aria-label="{e(title)}">']
    for k in range(5):
        v = lo + (hi - lo) * k / 4
        parts.append(f'<line class="l" x1="{pad_l}" x2="{width - 8}" y1="{y(v):.1f}" y2="{y(v):.1f}"/>'
                     f'<text x="{pad_l - 4}" y="{y(v) + 4:.1f}" text-anchor="end">{v:.0f}{unit}</text>')
    step = max(1, math.ceil(n / 24))
    for i, (lab, val) in enumerate(zip(labels, values, strict=True)):
        x = pad_l + slot * i + (slot - bw) / 2
        if val is not None and math.isfinite(val):
            parts.append(f'<rect x="{x:.1f}" y="{min(y(val), y(0)):.1f}" width="{bw:.1f}" height="{abs(y(val) - y(0)):.1f}" '
                         f'fill="{colour}"><title>{e(lab)}: {val:.2f}{unit}</title></rect>')
        if i % step == 0:
            parts.append(f'<text x="{x + bw / 2:.1f}" y="{height - 8}" text-anchor="middle">{e(lab)}</text>')
    parts.append("</svg>")
    return "".join(parts)


# ---------------------------------------------------------------- sections
def _tiles(items: list[tuple[str, str]]) -> str:
    return '<div class="tiles">' + "".join(f'<div class="tile"><b>{e(v)}</b><span>{e(k)}</span></div>' for k, v in items) + "</div>"


def _status(s: str, lang: str) -> str:
    cls = {"succeeded": "ok", "exported": "ok", "failed": "bad"}.get(s, "muted")
    return f'<span class="{cls}">{e(s)}</span>'


def overview(r: dict[str, Any], lang: str) -> str:
    sp, env = r.get("spec", {}), r.get("env", {})
    name = Path(str(sp.get("model_path") or r.get("model", {}).get("path") or "")).name
    base = (r.get("baseline") or {}).get("ppl")
    recs = r.get("recipes", {})
    tiles = [(T["model"][lang], name or "–"), (T["baseline_ppl"][lang], fmt(base, 3)),
             (T["n_recipes"][lang], str(len(recs))), ("job", str(r.get("job_id", "–")))]
    sub = " · ".join(x for x in (f"torch {env.get('torch')}" if env.get("torch") else "",
                                 f"device {env.get('device')}" if env.get("device") else "",
                                 f"threads {env.get('torch_threads')}" if env.get("torch_threads") else "") if x)
    return f'<h1>{e(T["title"][lang])}</h1><div class="sub">{e(sub)}</div>' + _tiles(tiles)


def recipes_section(r: dict[str, Any], lang: str) -> str:
    recs = r.get("recipes", {})
    if not recs:
        return ""
    base = (r.get("baseline") or {}).get("ppl")
    rows, names, ppls = [], [], []
    for n, rec in recs.items():
        s = rec.get("summary", {})
        wk = (rec.get("eval") or {}).get("fake_quant") or {}
        rows.append([f"<b>{e(n)}</b>", e(rec.get("algorithm", "–")), fmt(s.get("ppl"), 3), pct(s.get("ppl_delta_pct")),
                     fmt(wk.get("ppl"), 3) if wk else "–"])
        names.append(n)
        ppls.append(s.get("ppl"))
    chart = bar_chart([*names, "baseline"], [*ppls, base], T["ppl"][lang], height=180, colour="var(--b)") if base else ""
    head = [(T["recipe"][lang], False), (T["algorithm"][lang], False), (T["ppl"][lang], True), (T["delta"][lang], True),
            (T["kv"][lang], True)]
    return f'<div class="card"><h2>{e(T["recipes"][lang])}</h2>{chart}{table(head, rows)}</div>'


def logits_section(r: dict[str, Any], lang: str) -> str:
    probe = r.get("logits_probe")
    rows = [[f"<b>{e(n)}</b>", fmt(rec["logits"].get("kl"), 4), fmt(100 * rec["logits"].get("top1_agreement", float("nan")), 1) + "%",
             fmt(rec["logits"].get("ref_top1_prob_drop"), 4)] for n, rec in r.get("recipes", {}).items() if rec.get("logits")]
    if not probe or not rows:
        return ""
    head = [(T["recipe"][lang], False), (T["kl"][lang], True), (T["top1"][lang], True), (T["top1drop"][lang], True)]
    scope = f'{probe.get("windows")} × {probe.get("seq_len")} tokens'
    note = "" if probe.get("exact") else f'<p class="note">{e(T["kl_lower_bound"][lang].format(k=probe.get("k")))}</p>'
    return f'<div class="card"><h2>{e(T["logits"][lang])}</h2><p class="note">{e(scope)}</p>{table(head, rows)}{note}</div>'


def stages_section(r: dict[str, Any], lang: str) -> str:
    st = r.get("stages") or []
    if not st:
        return ""
    rows = [[e(s.get("stage")), _status(str(s.get("status")), lang), fmt(s.get("seconds"), 1)] for s in st]
    head = [(T["stage"][lang], False), (T["status"][lang], False), (T["seconds"][lang], True)]
    return f'<div class="card"><h2>{e(T["stages"][lang])}</h2>{table(head, rows)}</div>'


def layers_section(r: dict[str, Any], lang: str) -> str:
    out = []
    for n, rec in r.get("recipes", {}).items():
        ls = [x for x in rec.get("layers", []) if x.get("out_sqnr_db") is not None]
        if not ls:
            continue
        blocks: dict[int, list[float]] = {}
        for x in ls:
            if x.get("block") is not None:
                blocks.setdefault(int(x["block"]), []).append(float(x["out_sqnr_db"]))
        chart = ""
        if blocks:
            ks = sorted(blocks)
            chart = bar_chart([str(k) for k in ks], [sum(blocks[k]) / len(blocks[k]) for k in ks], T["by_block"][lang], unit=" dB")
        worst = sorted(ls, key=lambda x: x["out_sqnr_db"])[:10]
        rows = [[f'<span class="mono">{e(x["name"])}</span>', fmt(x["out_sqnr_db"], 1), fmt(x.get("w_sqnr_db"), 1),
                 fmt(x.get("act_kurtosis"), 0)] for x in worst]
        head = [(T["layer"][lang], False), ("out SQNR dB", True), ("w SQNR dB", True), ("act kurtosis", True)]
        out.append(f'<div class="card"><h2>{e(T["layers"][lang])} · {e(n)}</h2><p class="note">{e(T["by_block"][lang])}</p>{chart}'
                   f'<h2 style="margin-top:16px">{e(T["worst"][lang])}</h2>{table(head, rows)}</div>')
    return "".join(out)


def export_section(r: dict[str, Any], lang: str) -> str:
    rows = []
    for n, rec in r.get("recipes", {}).items():
        for f, ex in (rec.get("export") or {}).items():
            rc = ex.get("real_check") or {}
            if ex.get("status") != "exported":
                reason = ((ex.get("problems") or [{}])[0]).get("reason", "")
                bad = f'<span class="bad">{e(ex.get("status"))}</span>'
                rows.append([e(n), f"<code>{e(f)}</code>", bad, "–", "–", "–", "–", e(reason)])
                continue
            ok = rc.get("codes_identical")
            rows.append([e(n), f"<code>{e(f)}</code>", _status("exported", lang), nbytes(ex.get("bytes")),
                         f'<span class="{"ok" if ok else "bad"}">{e(T["yes"][lang] if ok else T["no"][lang])}</span>',
                         fmt(ex.get("real_ppl"), 3), pct(ex.get("real_vs_fake_ppl_pct")), ""])
    if not rows:
        return ""
    head = [(T["recipe"][lang], False), (T["format"][lang], False), (T["status"][lang], False), (T["size"][lang], True),
            (T["codes"][lang], False), (T["real_ppl"][lang], True), (T["vs_fake"][lang], True), ("", False)]
    return f'<div class="card"><h2>{e(T["export"][lang])}</h2>{table(head, rows)}</div>'


def vllm_section(r: dict[str, Any], lang: str) -> str:
    rows = []
    for n, rec in r.get("recipes", {}).items():
        for f, ex in (rec.get("export") or {}).items():
            v = ex.get("vllm")
            if not v:
                continue
            if v.get("status") in ("skipped", "failed"):
                why = v.get("diagnosis") or v.get("reason") or str(v.get("error", "")).splitlines()[:1]
                label = T.get(v["status"], {}).get(lang, v["status"])
                rows.append([e(n), f"<code>{e(f)}</code>", f'<span class="bad">{e(label)}</span>', *["–"] * 7, e(why)])
                continue
            ld, en = v.get("load") or {}, v.get("engine") or {}
            rows.append([e(n), f"<code>{e(f)}</code>", _status(str(v.get("status")), lang), e(en.get("quant_kernel", "–")),
                         fmt(v.get("startup_s"), 0), fmt(v.get("served_ppl"), 3), pct(v.get("served_vs_real_ppl_pct")),
                         fmt((ld.get("ttft_ms") or {}).get("p50"), 0), fmt((ld.get("tpot_ms") or {}).get("p50"), 1),
                         fmt(ld.get("output_tokens_per_s"), 0)])
    if not rows:
        return ""
    head = [(T["recipe"][lang], False), (T["format"][lang], False), (T["status"][lang], False), (T["kernel"][lang], False),
            (T["startup"][lang], True), (T["served_ppl"][lang], True), (T["vs_real"][lang], True), ("TTFT p50 ms", True),
            ("TPOT p50 ms", True), (T["tps"][lang], True)]
    if any(len(x) > len(head) for x in rows):
        head.append(("", False))
        rows = [x + [""] * (len(head) - len(x)) for x in rows]
    return f'<div class="card"><h2>{e(T["vllm"][lang])}</h2>{table(head, rows)}</div>'


def gguf_section(r: dict[str, Any], lang: str) -> str:
    ll = r.get("llamacpp")
    if not ll or not ll.get("results"):
        return ""
    res = ll["results"]
    f16 = res.get("f16", {}).get("ppl")
    rows = []
    for t, x in res.items():
        pp = next((v for k, v in x.items() if k.startswith("pp") and k.endswith("_tokens_per_s")), None)
        tg = next((v for k, v in x.items() if k.startswith("tg") and k.endswith("_tokens_per_s")), None)
        sv = (x.get("serve") or {}).get("load") or {}
        rows.append([f"<b>{e(t.upper())}</b>", nbytes(x.get("bytes")), fmt(x.get("ppl"), 3),
                     pct(100 * (x["ppl"] / f16 - 1)) if f16 and t != "f16" else "–", fmt(pp, 0), fmt(tg, 1),
                     fmt(sv.get("output_tokens_per_s"), 0), fmt((sv.get("ttft_ms") or {}).get("p50"), 0)])
    head = [(T["type"][lang], False), (T["size"][lang], True), ("PPL", True), ("vs F16", True), (T["prefill"][lang], True),
            (T["decode"][lang], True), (T["tps"][lang] + " (server)", True), ("TTFT p50 ms (server)", True)]
    note = f'<p class="note">{e(ll.get("protocol", ""))}</p>'
    return f'<div class="card"><h2>{e(T["gguf"][lang])}</h2>{table(head, rows)}{note}</div>'


def sensitivity_section(r: dict[str, Any], lang: str) -> str:
    out = []
    for n, rec in r.get("recipes", {}).items():
        s = rec.get("sensitivity")
        if not s:
            continue
        groups = sorted(s.get("groups", []), key=lambda g: -g.get("recovered", 0))[:12]
        rows = [[f'<span class="mono">{e(g["group"])}</span>', fmt(g.get("layers")), fmt(g.get("metric"), 3), fmt(g.get("recovered"), 3)]
                for g in groups]
        head = [(T["group"][lang], False), ("layers", True), (s.get("metric", "metric"), True), (T["recovered"][lang], True)]
        rules = (s.get("suggestion") or {}).get("rules") or []
        rtxt = f'<p class="note">{e(T["rules"][lang])}: <code>{e(json.dumps(rules, ensure_ascii=False))}</code></p>' if rules else ""
        out.append(f'<div class="card"><h2>{e(T["sens"][lang])} · {e(n)}</h2>{table(head, rows)}{rtxt}</div>')
    return "".join(out)


def render_html(report: dict[str, Any], lang: str = "en") -> str:
    if lang not in ("zh", "en"):
        raise ValueError("lang must be 'zh' or 'en'")
    if report.get("kind") not in (None, "llm"):
        raise ValueError(f"only LLM job reports are supported (kind={report.get('kind')!r})")
    body = "".join(f(report, lang) for f in (overview, recipes_section, logits_section, layers_section, export_section, vllm_section,
                                              gguf_section, sensitivity_section, stages_section))
    title = f'{T["title"][lang]} · {report.get("job_id", "")}'
    return (f'<!doctype html><html lang="{lang}"><head><meta charset="utf-8">'
            f'<meta name="viewport" content="width=device-width,initial-scale=1">'
            f'<title>{e(title)}</title><style>{CSS}</style></head><body><main>{body}'
            f'<p class="note">{e(T["footer"][lang])}</p></main></body></html>')


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("report", help="path to a job's report.json")
    ap.add_argument("-o", "--out", help="output file (default: next to the report as report.<lang>.html)")
    ap.add_argument("--lang", choices=["zh", "en"], default="en")
    a = ap.parse_args()
    src = Path(a.report)
    out = Path(a.out) if a.out else src.with_name(f"report.{a.lang}.html")
    out.write_text(render_html(json.loads(src.read_text()), a.lang), encoding="utf-8")
    print(out)


if __name__ == "__main__":
    main()
