#!/usr/bin/env python3
"""Generate data/datasets/evalscope_catalog.yaml from the vendored EvalScope docs table.

The table is the authoritative list EvalScope ships in
``3rdpart/evalscope/docs/zh/get_started/supported_dataset/llm.md``.  We only copy public metadata
(name, display name, tags, docs link); evaluation still runs through EvalScope itself.
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "3rdpart/evalscope/docs/zh/get_started/supported_dataset/llm.md"
OUT = ROOT / "data/datasets/evalscope_catalog.yaml"
DOC_BASE = "https://evalscope.readthedocs.io/zh-cn/latest/benchmarks/"

ROW = re.compile(r"^\|\s*`([^`]+)`\s*\|\s*\[([^\]]+)\]\(([^)]+)\)\s*\|\s*(.*?)\s*\|\s*$")


def group_for(tags: list[str]) -> str:
    t = set(tags)
    for key, group in [
        ("MultiModal", "多模态"), ("Agent", "Agent"), ("Coding", "代码"),
        ("Math", "数学"), ("LongContext", "长上下文"), ("Chinese", "中文"),
        ("InstructionFollowing", "指令遵循"), ("Medical", "医学"),
        ("FunctionCalling", "工具调用"), ("NER", "信息抽取"),
        ("Arena", "对话竞技"), ("QA", "问答"), ("Hallucination", "真实性"),
        ("Knowledge", "知识"), ("Reasoning", "推理"),
    ]:
        if key in t:
            return group
    return "其他"


def main() -> None:
    rows = []
    for line in SRC.read_text(encoding="utf-8").splitlines():
        m = ROW.match(line)
        if not m:
            continue
        name, label, href, raw_tags = m.groups()
        tags = [x.strip().strip("`") for x in raw_tags.split(",") if x.strip()]
        rows.append((name, label.strip(), href.strip(), tags, group_for(tags)))
    rows.sort(key=lambda r: (r[4], r[0]))
    lines = [
        "# Generated by scripts/gen_evalscope_catalog.py from 3rdpart/evalscope docs.",
        "# Metadata only: running one of these datasets requires the EvalScope CLI and a served model.",
        "source: evalscope",
        "datasets:",
    ]
    for name, label, href, tags, group in rows:
        doc = href if href.startswith("http") else DOC_BASE + href.rsplit("/", 1)[-1]
        lines += [
            f"  - name: {name}",
            f"    label: \"{label}\"",
            f"    group: \"{group}\"",
            f"    tags: [{', '.join(tags)}]",
            f"    docs: {doc}",
            "    runner: evalscope",
            "    offline: false",
        ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} datasets")


if __name__ == "__main__":
    main()
